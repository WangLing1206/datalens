"""
Package the source tree into the submission zip.

Excludes build output, dependencies and caches; includes the sample datasets,
tooling scripts, tests, fixtures, screenshots, the demo video and the document.

Run:  python tools/package.py
Out:  deliverables/DataLens-源码.zip
"""
from __future__ import annotations

import os
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "deliverables")
os.makedirs(OUT, exist_ok=True)

# `deliverables` holds the finished artefacts: the write-up ships inside the
# archive, the archive itself obviously cannot, and the video is already packed
# from tools/video/out. `shots` is handled by `included()` too — its top-level
# PNGs are referenced by the Markdown write-up.
EXCLUDE_DIRS = {
    "node_modules", "dist", ".git", ".vite", "test-results", "playwright-report",
    "__pycache__", ".vercel", "frames", ".zcode",
}
KEEP_FROM_DELIVERABLES = {"DataLens-亮点说明.docx", "DataLens-highlights.md"}
EXCLUDE_EXT = {".log", ".pyc", ".tmp", ".tsbuildinfo"}
# Intermediate video assets are large and reproducible from the script.
EXCLUDE_FILES = {
    "audio-list.txt", "narration.mp3", "narration.wav", "recorded.json", "tts.json",
    "scenes.json", "timeline.json", "durations.json", "record.json", "demo.webm",
    "calibration.json",
}


OUTPUT_ZIP = os.path.join(OUT, "DataLens-源码.zip")


def included(path: str) -> bool:
    if os.path.abspath(path) == os.path.abspath(OUTPUT_ZIP):
        return False
    rel = os.path.relpath(path, ROOT)
    parts = rel.split(os.sep)
    # Keep the documented screenshots (shots/*.png) — the Markdown version of
    # the write-up links to them — but not the bulk audit/tooling captures.
    if parts[0] == "shots":
        return len(parts) == 2 and parts[1].endswith(".png")
    if parts[0] == "deliverables":
        return len(parts) == 2 and parts[1] in KEEP_FROM_DELIVERABLES
    if any(p in EXCLUDE_DIRS for p in parts):
        return False
    if os.path.splitext(path)[1].lower() in EXCLUDE_EXT:
        return False
    if os.path.basename(path) in EXCLUDE_FILES:
        return False
    if os.path.basename(path).startswith("page@") and path.endswith(".webm"):
        return False
    # Per-scene padded audio (tools/video/mux.py) — regenerated by the script.
    if os.path.basename(path).startswith("pad-") and path.endswith(".wav"):
        return False
    if os.path.basename(path).startswith("seg-") and path.endswith((".mp3", ".wav")):
        return False
    if os.path.basename(path).startswith("_demo."):
        return False
    return True


def main() -> None:
    out = os.path.join(OUT, "DataLens-源码.zip")
    count = 0
    total = 0

    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for dirpath, dirnames, filenames in os.walk(ROOT):
            dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
            for name in filenames:
                full = os.path.join(dirpath, name)
                if not included(full):
                    continue
                arc = os.path.join("DataLens", os.path.relpath(full, ROOT)).replace(os.sep, "/")
                z.write(full, arc)
                count += 1
                total += os.path.getsize(full)

    size = os.path.getsize(out)
    print(f"packed {count} files  ({total / 1024 / 1024:.1f} MB raw)")
    print(f"wrote  {out}  ({size / 1024 / 1024:.1f} MB zip)")

    # Show the top-level layout so the structure is obvious in the log.
    with zipfile.ZipFile(out) as z:
        tops: dict[str, int] = {}
        for n in z.namelist():
            parts = n.split("/")
            if len(parts) > 1:
                key = parts[1] if len(parts) > 2 else parts[-1]
                tops[key] = tops.get(key, 0) + 1
        print("\ntop-level entries:")
        for k in sorted(tops)[:30]:
            print(f"  {k}")


if __name__ == "__main__":
    main()
